// Launchers declared + no Service.qml: the stub service is created, registered
// in the manifest and paired with the writer helper.
func TestLauncherServiceCreatesStub(t *testing.T) {
	dir := t.TempDir()
	project := filepath.Join(dir, "p")
	if _, err := scaffoldWithOptions(project, []string{"panel"}, scaffoldOptions{Author: "tester"}); err != nil {
		t.Fatal(err)
	}
	writeOMAConfig(t, project, `{"launchers":[{"name":"App","action":"toggle"}]}`)

	if err := ensureLauncherService(project); err != nil {
		t.Fatal(err)
	}

	stub, err := os.ReadFile(filepath.Join(project, "ui", "Service.qml"))
	if err != nil {
		t.Fatal(err)
	}
	ss := string(stub)
	if !strings.Contains(ss, launcherWriterMarker) || !strings.Contains(ss, "LauncherWriter {}") {
		t.Fatalf("stub service missing marker or writer instantiation:\n%s", ss)
	}

	helper, err := os.ReadFile(filepath.Join(project, "ui", "LauncherWriter.qml"))
	if err != nil {
		t.Fatal(err)
	}
	hs := string(helper)
	for _, want := range []string{launcherWriterMarker, "tester.p.desktop", "bash"} {
		if !strings.Contains(hs, want) {
			t.Errorf("LauncherWriter missing %q", want)
		}
	}

	m, err := readManifest(filepath.Join(project, "manifest.json"))
	if err != nil {
		t.Fatal(err)
	}
	if !contains(m.Kinds, "service") || m.EntryPoints["service"] != "ui/Service.qml" {
		t.Fatalf("manifest not registered: kinds=%v entryPoints=%v", m.Kinds, m.EntryPoints)
	}
}

// A custom (marker-less) Service.qml is preserved; only the helper is written
// and the manifest is not touched.
func TestLauncherServiceCustomKept(t *testing.T) {
	dir := t.TempDir()
	project := filepath.Join(dir, "p")
	if _, err := scaffoldWithOptions(project, []string{"panel"}, scaffoldOptions{Author: "tester"}); err != nil {
		t.Fatal(err)
	}
	writeOMAConfig(t, project, `{"launchers":[{"name":"App"}]}`)
	custom := "import QtQuick\nItem { id: root }\n"
	if err := os.WriteFile(filepath.Join(project, "ui", "Service.qml"), []byte(custom), 0o644); err != nil {
		t.Fatal(err)
	}

	if err := ensureLauncherService(project); err != nil {
		t.Fatal(err)
	}

	got, err := os.ReadFile(filepath.Join(project, "ui", "Service.qml"))
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != custom {
		t.Fatalf("custom Service.qml was modified:\n%s", got)
	}
	if _, err := os.Stat(filepath.Join(project, "ui", "LauncherWriter.qml")); err != nil {
		t.Fatal("helper not written for custom service")
	}
	m, _ := readManifest(filepath.Join(project, "manifest.json"))
	if contains(m.Kinds, "service") {
		t.Fatalf("custom service caused manifest registration: %v", m.Kinds)
	}
}

// Re-running over the generated stub regenerates the helper without
// duplicating the service kind.
func TestLauncherServiceRegeneration(t *testing.T) {
	dir := t.TempDir()
	project := filepath.Join(dir, "p")
	if _, err := scaffoldWithOptions(project, []string{"panel"}, scaffoldOptions{Author: "tester"}); err != nil {
		t.Fatal(err)
	}
	writeOMAConfig(t, project, `{"launchers":[{"name":"App"}]}`)
	if err := ensureLauncherService(project); err != nil {
		t.Fatal(err)
	}
	if err := ensureLauncherService(project); err != nil {
		t.Fatal(err)
	}

	m, err := readManifest(filepath.Join(project, "manifest.json"))
	if err != nil {
		t.Fatal(err)
	}
	if !contains(m.Kinds, "service") {
		t.Fatalf("service kind lost on regeneration: %v", m.Kinds)
	}
	if strings.Count(strings.Join(m.Kinds, ","), "service") != 1 {
		t.Fatalf("service kind duplicated: %v", m.Kinds)
	}
	if _, err := os.Stat(filepath.Join(project, "ui", "LauncherWriter.qml")); err != nil {
		t.Fatal("helper missing after regeneration")
	}
}
